//! Developer automation for the workspace. Run via `cargo xtask`.

use std::error::Error;
use std::path::{Path, PathBuf};
use std::process::ExitCode;
use std::{env, fs};

use kube::CustomResourceExt;
use secretspec_api::v1alpha1::SecretSpec;

/// Header written at the top of every generated CRD file.
const HEADER: &str = "# Generated by \"cargo xtask crdgen\". Do not edit.\n---\n";

/// CRD output path, relative to the workspace root.
const CRD_PATH: &str = "charts/secretspec-operator/files/crd/secretspecs.secretspec.jabbas.eu.yaml";

type BoxError = Box<dyn Error>;

/// Renders the `SecretSpec` CRD as deterministic YAML.
///
/// Key order is stable: structs serialize in declaration order and schema
/// maps are sorted (`BTreeMap`-backed), so repeated runs yield identical bytes.
fn render_crd() -> Result<String, BoxError> {
    let yaml = serde_norway::to_string(&SecretSpec::crd())?;
    let mut out = String::with_capacity(HEADER.len() + yaml.len() + 1);
    out.push_str(HEADER);
    out.push_str(&yaml);
    if !out.ends_with('\n') {
        out.push('\n');
    }
    Ok(out)
}

/// Workspace root, derived from this crate's manifest dir (not the cwd).
fn workspace_root() -> Result<PathBuf, BoxError> {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .map(Path::to_path_buf)
        .ok_or_else(|| "cannot determine workspace root".into())
}

fn crdgen(check: bool) -> Result<ExitCode, BoxError> {
    let path = workspace_root()?.join(CRD_PATH);
    let rendered = render_crd()?;
    if check {
        let current = fs::read_to_string(&path).unwrap_or_default();
        if current == rendered {
            println!("{CRD_PATH} is up to date");
            return Ok(ExitCode::SUCCESS);
        }
        eprintln!("error: {CRD_PATH} is out of date or missing.");
        eprintln!("Run `cargo xtask crdgen` and commit the result.");
        return Ok(ExitCode::FAILURE);
    }
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    fs::write(&path, rendered)?;
    println!("wrote {CRD_PATH}");
    Ok(ExitCode::SUCCESS)
}

fn run() -> Result<ExitCode, BoxError> {
    let args: Vec<String> = env::args().skip(1).collect();
    match args
        .iter()
        .map(String::as_str)
        .collect::<Vec<_>>()
        .as_slice()
    {
        ["crdgen"] => crdgen(false),
        ["crdgen", "--check"] => crdgen(true),
        _ => {
            eprintln!("usage: cargo xtask crdgen [--check]");
            Ok(ExitCode::from(2))
        }
    }
}

fn main() -> ExitCode {
    match run() {
        Ok(code) => code,
        Err(err) => {
            eprintln!("error: {err}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use k8s_openapi::apiextensions_apiserver::pkg::apis::apiextensions::v1::CustomResourceDefinition;

    #[test]
    fn rendered_crd_is_deterministic() {
        let first = render_crd().expect("render");
        let second = render_crd().expect("render");
        assert_eq!(first.as_bytes(), second.as_bytes());
        assert!(first.starts_with(HEADER));
        assert!(first.ends_with('\n'));

        let crd: CustomResourceDefinition = serde_norway::from_str(&first).expect("parse");
        assert_eq!(
            crd.metadata.name.as_deref(),
            Some("secretspecs.secretspec.jabbas.eu")
        );
    }
}
